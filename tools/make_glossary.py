def compose(name):
    for suf, ko in SUFFIX.items():
        if name.endswith(suf) and name != suf:
            head = name[:-len(suf)]
            if head in COMP: return COMP[head] + ' ' + ko
    return None


def main():
    v2 = json.load(open(V2_GLOSS, encoding='utf-8'))
    dlg = json.load(open(os.path.join(ROOT, 'work/translation/dialogue.json'), encoding='utf-8'))
    sj = json.load(open(os.path.join(ROOT, 'work/translation/sjis-all.json'), encoding='utf-8'))
    texts = [x['jp'] for x in dlg] + [x['jp'] for x in sj['strings'] if x['class'] == 'display'] + [x['jp'] for x in sj['unreferenced']]
    alltxt = '\n'.join(texts)
    cores = json.load(open(os.path.join(ROOT, 'work/glossary/name-cores.json'), encoding='utf-8'))
    out = {}
    def appears(jp):
        # 가타카나 낱말은 앞뒤가 가타카나가 아닐 때만(レベル 안의 ベル 같은 우연 제외)
        if re.fullmatch(r'[ァ-ヶー・]+', jp):
            return re.search(r'(?<![ァ-ヶー])' + re.escape(jp) + r'(?![ァ-ヶー])', alltxt) is not None
        return jp in alltxt
    for jp, e in v2.items():
        if len(jp) >= 2 and appears(jp):
            out[jp] = {'ko': e['ko'], 'cat': e.get('cat', ''), 'src': e.get('src', 'v2'), 'note': ''}
    for jp, (ko, cat, note) in NEW.items():
        if jp in out and out[jp]['ko'] != ko:
            note = (note + '; ' if note else '') + '1편/V2: ' + out[jp]['ko']
        out[jp] = {'ko': ko, 'cat': cat, 'src': 'gx', 'note': note}
    for jp, ko in PARTS_EXTRA.items():
        out.setdefault(jp, {'ko': ko, 'cat': '파츠', 'src': 'gx', 'note': ''})
    unresolved = []
    for name in cores:
        if name in out: continue
        ko = compose(name)
        if ko: out[name] = {'ko': ko, 'cat': '파츠', 'src': 'gx', 'note': '낱말 조합'}
        elif re.search(r'(ガン|ボム|ポッド|ガンナー|プロテクター)$', name): unresolved.append(name)
    def count(jp):
        if re.fullmatch(r'[ァ-ヶー・]+', jp):
            return len(re.findall(r'(?<![ァ-ヶー])' + re.escape(jp) + r'(?![ァ-ヶー])', alltxt))
        return alltxt.count(jp)
    for jp, e in out.items(): e['count'] = count(jp)
    os.makedirs(os.path.join(ROOT, 'work/glossary'), exist_ok=True)
    json.dump(out, open(os.path.join(ROOT, 'work/glossary/glossary-ko.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
    by = collections.defaultdict(list)
    for jp, e in out.items(): by[e['cat'] or '기타'].append((jp, e))
    lines = ['# GX 용어집 초안 (5단계, 2026-10-23)', '',
             '`work/glossary/glossary-ko.json`에서 만든 읽기용 표. src: v1=1편, v2=V2, gx=GX 새 항목. 횟수=GX 텍스트에 나온 수.', '']
    for cat in sorted(by, key=lambda c: -len(by[c])):
        lines += ['## ' + cat + ' (%d)' % len(by[cat]), '', '| 원문 | 번역 | 출처 | 횟수 | 메모 |', '|---|---|---|---:|---|']
        for jp, e in sorted(by[cat], key=lambda x: -x[1]['count']):
            lines.append('| %s | %s | %s | %d | %s |' % (jp, e['ko'], e['src'], e['count'], e['note']))
        lines.append('')
    open(os.path.join(ROOT, 'docs/glossary.md'), 'w', encoding='utf-8').write('\n'.join(lines))
    print('항목', len(out), collections.Counter(e['src'] for e in out.values()))
    print('못 정한 파츠 이름', unresolved)


if __name__ == '__main__':
    main()
